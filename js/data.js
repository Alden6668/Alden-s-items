const audioText = (book) =>
  [
    book.oneLiner,
    book.intro,
    ...book.whyRead,
    ...book.keyIdeas.map((k) => `${k.title}。${k.body}`),
    ...book.sections.flatMap((s) => [s.title, ...s.paras, s.takeaway]),
    ...book.actions,
    book.debate.body,
    book.audience,
    ...book.quotes.map((q) => q.text),
  ].join('');

export const BOOKS = rawBooks.map((book, index) => {
  const text = audioText(book);
  const chars = text.length;
  return {
    ...book,
    index: index + 1,
    chars,
    listenMinutes: Math.max(4, Math.round((chars / 238) * 10) / 10),
    readMinutes: Math.max(4, Math.round(chars / 480)),
  };
});

export const allBooks = () => [...BOOKS, ...(store.get().importedBooks || [])];

export const getBook = (id) => allBooks().find((b) => b.id === id);

export function computeBookMetrics(book) {
  const text = [
    book.oneLiner,
    book.intro,
    ...(book.whyRead || []),
    ...(book.keyIdeas || []).map((item) => `${item.title}。${item.body}`),
    ...(book.sections || []).flatMap((section) => [section.title, ...(section.paras || []), section.takeaway]),
    ...(book.actions || []),
    book.debate?.body || '',
    book.audience || '',
    ...(book.quotes || []).map((quote) => quote.text),
  ].join('');
  const chars = text.length;
  return {
    chars,
    listenMinutes: Math.max(3, Math.round((chars / 238) * 10) / 10),
    readMinutes: Math.max(2, Math.round(chars / 480)),
  };
}

export const searchBooks = (query) => {
  const q = query.trim().toLowerCase();
  const list = allBooks();
  if (!q) return list;
  return list.filter((book) => {
    const haystack = [
      book.title,
      book.enTitle,
      book.author,
      book.oneLiner,
      book.intro,
      book.tagline,
      ...book.tags,
      ...book.keyIdeas.map((k) => `${k.title} ${k.body}`),
      categoryOf(book.category).name,
    ]
      .join(' ')
      .toLowerCase();
    return haystack.includes(q);
  });
};
